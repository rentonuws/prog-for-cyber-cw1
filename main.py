import security_tools  #importing the security_tools module

valid = False

while not valid: #loop until a valid password is entered
    password = input("Please enter a password: ") #prompt the user to enter a password
    if security_tools.check(password): #check if the password meets the criteria defined in the check function
        print("Password accepted") #print a message indicating that the password is accepted
        valid = True
    else:
        print(f"Password doesn't match the minimum requirement, please use this password instead: {security_tools.random_password()}") #print a message indicating that the password doesn't meet the criteria and suggest a random password generated by the random_password function
        print("Please enter the generated password or create a new one that meets the criteria") #prompt the user to enter the generated password or create a new one that meets the criteria
valid = False

while not valid: #loop until a valid IP address is entered
    ip = input("Please enter an IP address: ") #prompt the user to enter an IP address
    if security_tools.validate_ip(ip): #check if the IP address is valid
        print("Valid IP address") #print a message indicating that the IP address is valid
        valid = True
    else:
        print("Invalid IP address") #print a message indicating that the IP address is invalid